#[derive(Debug, Deserialize, Serialize)]
struct ShardAssignment {
    market_id: String,
    shard: usize,
}

#[derive(Debug, Deserialize, Serialize)]
struct ShardMapFixture {
    shard_count: usize,
    distribution: [usize; 4],
    assignments: Vec<ShardAssignment>,
}

fn compute_fixture(shard_count: usize) -> ShardMapFixture {
    let mut distribution = [0usize; 4];
    let mut assignments = Vec::with_capacity(MARKET_IDS.len());
    for market_id in MARKET_IDS {
        let shard = shard_index(market_id, shard_count);
        distribution[shard] += 1;
        assignments.push(ShardAssignment {
            market_id: market_id.to_owned(),
            shard,
        });
    }
    ShardMapFixture {
        shard_count,
        distribution,
        assignments,
    }
}

#[test]
fn shard_assignment_matches_golden_snapshot() {
    let fixture: ShardMapFixture = serde_json::from_str(include_str!("fixtures/shard_map_4.json"))
        .expect("parse shard_map_4.json");
    assert_eq!(fixture.shard_count, 4);

    let live = compute_fixture(4);
    assert_eq!(live.distribution, fixture.distribution);
    assert_eq!(live.assignments.len(), fixture.assignments.len());

    for (computed, expected) in live.assignments.iter().zip(fixture.assignments.iter()) {
        assert_eq!(computed.market_id, expected.market_id);
        assert_eq!(computed.shard, expected.shard);
    }
}

#[test]
fn shard_distribution_within_thirty_percent_of_uniform() {
    let fixture = compute_fixture(4);
    let expected_per_shard = MARKET_IDS.len() / 4;
    let tolerance = expected_per_shard.saturating_mul(30).div_ceil(100);
    let min = expected_per_shard.saturating_sub(tolerance);
    let max = expected_per_shard + tolerance;

    for (shard, count) in fixture.distribution.iter().enumerate() {
        assert!(
            (*count >= min && *count <= max),
            "shard {shard} count {count} outside [{min}, {max}]"
        );
    }
}

