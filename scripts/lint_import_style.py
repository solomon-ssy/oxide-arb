def strip_strings_and_comments(line: str, in_block_comment: bool) -> tuple[str, bool]:
    """Return code-only text for brace/`use` detection; track /* */ state."""
    if in_block_comment:
        end = line.find("*/")
        if end < 0:
            return "", True
        line = line[end + 2 :]
        in_block_comment = False

    out: list[str] = []
    i = 0
    n = len(line)
    in_string = False
    in_char = False
    while i < n:
        ch = line[i]
        nxt = line[i + 1] if i + 1 < n else ""

        if not in_string and not in_char:
            if ch == "/" and nxt == "/":
                break
            if ch == "/" and nxt == "*":
                end = line.find("*/", i + 2)
                if end < 0:
                    return "".join(out), True
                i = end + 2
                continue
            if ch == '"':
                in_string = True
                out.append(" ")
                i += 1
                continue
            if ch == "'":
                if nxt.isalpha() or nxt == "_":
                    out.append(ch)
                    i += 1
                    continue
                in_char = True
                out.append(" ")
                i += 1
                continue
            out.append(ch)
            i += 1
            continue

        if in_string:
            if ch == "\\" and i + 1 < n:
                i += 2
                continue
            if ch == '"':
                in_string = False
            i += 1
            continue

        if ch == "\\" and i + 1 < n:
            i += 2
            continue
        if ch == "'":
            in_char = False
        i += 1

    return "".join(out), in_block_comment


def strip_for_path_scan(line: str) -> str:
    """Remove strings, line comments, and rustdoc link targets for path matching."""
    s = re.sub(r"\[[^\]]*\]\([^)]*\)", " ", line)
    s = re.sub(
        r"\[(?:crate|super|self|std|core|alloc|quant_pivot_[a-z0-9_]+)(?:::[^\]]+)?\]",
        " ",
        s,
    )
    code, _ = strip_strings_and_comments(s, False)
    return code


def iter_rs_files() -> list[Path]:
    files: list[Path] = []
    for src in SRC_ROOTS:
        crate = src.parent.name
        if crate in EXCLUDE_CRATES:
            continue
        for path in sorted(src.rglob("*.rs")):
            # SeaORM relation fields intentionally use sibling-module paths such
            # as `super::market::Entity`. Keeping generated entities byte-close
            # to codegen output makes schema regeneration reviewable; rustfmt,
            # compilation, and clippy remain the quality gates for these files.
            header = path.read_text(encoding="utf-8", errors="replace")[:256]
            if SEAORM_CODEGEN_MARKER in header:
                continue
            files.append(path)
    return files


